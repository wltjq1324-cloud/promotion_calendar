def part_sku(p):
    mult = 1
    for m in re.finditer(r'\((\d+)\s*EA\)', p): mult *= int(m.group(1))
    m = re.search(r'(?:\*|x)\s*(\d+)\s*봉?\s*$', p.strip())
    if m: mult *= int(m.group(1))
    s = re.sub(r'\s+', '', p)
    for keys, name in RULES:
        if all(k in s for k in keys): return name, mult
    return '?', mult

def decompose(prod):
    """표준품목명 → Counter{단품명: 개수}. 못 푼 조각은 '?' 로 남긴다."""
    out = collections.Counter()
    # 세트명 안의 괄호 쉼표(프리미엄 선물 세트(감자4개입,…))는 한 덩어리로 둔다
    for part in prod.split('+'):
        name, mult = part_sku(part)
        if name is None: continue
        # [G] 선물세트 묶음의 옥수수빵 3개입은 옛 선물세트 상품이다
        if '[G]' in prod and name == '초당옥수수빵 100g 3개입': name = '선물세트 100g 초당옥수수빵 3개입'
        out[name] += mult
    return out

